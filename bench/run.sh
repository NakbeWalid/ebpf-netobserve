#!/bin/bash
# Overhead benchmark: connection spam on loopback WITHOUT vs WITH netobserve.
#
#   bash bench/run.sh                 full benchmark (asks for sudo)
#   SKIP_TRACER=1 bash bench/run.sh   baseline only, no root needed
#   RUNS=5 CONNS=20000                tunables (environment variables)
#
# Runs are interleaved (baseline, traced, baseline, traced, ...) so that a
# slow drift of the machine affects both sides equally.
# Raw lines go to bench/raw/, the table to bench/RESULTS.md.
set -eu
cd "$(dirname "$0")/.."

RUNS="${RUNS:-5}"
CONNS="${CONNS:-20000}"
SKIP_TRACER="${SKIP_TRACER:-0}"
PORT=9401 # metrics port of the tracer during the benchmark
RAW=bench/raw

if [ ! -x bench/connspam ] || [ ! -x netobserve ]; then
	echo "build first: make && make bench" >&2
	exit 1
fi
mkdir -p "$RAW"
: > "$RAW/baseline.txt"
: > "$RAW/traced.txt"

# CPU seconds (user + system) used so far by the netobserve process:
# fields 14 and 15 of /proc/<pid>/stat, in clock ticks.
tracer_cpu() {
	awk -v hz="$(getconf CLK_TCK)" '{ printf "%.2f", ($14 + $15) / hz }' \
		"/proc/$(pgrep -x netobserve)/stat"
}

[ "$SKIP_TRACER" = 1 ] || sudo -v

for i in $(seq "$RUNS"); do
	echo "run $i/$RUNS: baseline"
	./bench/connspam "$CONNS" >> "$RAW/baseline.txt"

	[ "$SKIP_TRACER" = 1 ] && continue
	echo "run $i/$RUNS: traced"
	sudo ./netobserve -q -p "$PORT" > /dev/null &
	sleep 1
	line="$(./bench/connspam "$CONNS")"
	sleep 0.5 # let the tracer drain the ring buffer
	echo "$line tracer_cpu_s=$(tracer_cpu)" >> "$RAW/traced.txt"
	sudo pkill -INT -x netobserve
	wait
done

# Print "mean ± stddev" of key $1 over all lines of file $2.
stat() {
	awk -v key="$1" '
	{
		for (i = 1; i <= NF; i++) {
			split($i, kv, "=")
			if (kv[1] == key) { n++; sum += kv[2]; sq += kv[2] * kv[2] }
		}
	}
	END {
		if (n == 0) { print "not measured"; exit }
		mean = sum / n
		sd = n > 1 ? sqrt((sq - n * mean * mean) / (n - 1)) : 0
		if (sd != sd) sd = 0 # NaN from rounding when all values are equal
		printf "%.2f ± %.2f", mean, sd
	}' "$2"
}

row() { echo "| $1 | $(stat "$2" "$RAW/baseline.txt") | $(stat "$2" "$RAW/traced.txt") |"; }

{
	echo "# Benchmark results"
	echo
	echo "Generated by \`bench/run.sh\` on $(date -u +%Y-%m-%d), kernel $(uname -r)."
	echo
	echo "> Runs on virtualized WSL2: absolute numbers are indicative only."
	echo "> Compare the two columns, not the values themselves."
	echo
	echo "$RUNS runs per column, $CONNS sequential loopback connections per run."
	echo "Values are mean ± sample standard deviation."
	echo
	echo "| Metric | Without tracer | With tracer |"
	echo "|---|---|---|"
	row "Throughput (connections/s)" rate
	row "Mean connect latency (us)" mean_us
	row "p99 connect latency (us)" p99_us
	row "Load CPU time, client + server (s)" cpu_s
	row "Tracer CPU time (s)" tracer_cpu_s
	if [ "$SKIP_TRACER" = 1 ]; then
		echo
		echo "**Baseline only (SKIP_TRACER=1): the \"With tracer\" column was NOT measured.**"
	fi
} > bench/RESULTS.md
cat bench/RESULTS.md
